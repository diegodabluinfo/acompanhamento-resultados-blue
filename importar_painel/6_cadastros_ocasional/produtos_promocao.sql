SELECT e.FILIAL, e.GRUPO, e.CODIGO, e.TIPO, e.DESCONTO, e.ORDEM, e.CATEGORIA, e.DATAHORAINICIO, e.DATAHORAFIM, e.VALOR_SUGESTAO,
       e.CAMPANHA, e.TIPO_DESCONTO, COALESCE(NULLIF(TRIM(e.TIPO_REBATE), ''), '-') AS TIPO_REBATE,
       e.QTD_MAXIMA, e.QTD_MAX_CLIENTE, e.QTD_VENDIDA, e.APLICACAO,
       CAST(1 AS INTEGER) AS SQL_VERSAO
  FROM ESPECIAL e
 WHERE e.FILIAL = 'BLUE'
 ORDER BY e.GRUPO, e.CODIGO
