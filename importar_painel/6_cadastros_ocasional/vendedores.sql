SELECT v.CODVEND AS CODIGO, v.NOME, v.ATIVO, v.EMAIL, v.FONE1, v.FONE2, v.FAX, v.ENDERECO, v.BAIRRO, v.CIDADE, v.UF, v.CEP,
       v.CPF, v.RG, v.COMISSAO, v.COMISSAO_EXT, v.COMISSAO_2, v.REGRA_COMISSAO, v.MAXIMO_DESCONTO, v.META1, v.META2, v.META3,
       v.GERENTE, v.GERENTE_SN, v.IDUSER, v.MSN, CAST(SUBSTRING(v.ASSINATURA FROM 1 FOR 255) AS VARCHAR(255)) AS ASSINATURA, v.DIFAL_POR_UF, v.FILIAL,
       CAST(1 AS INTEGER) AS SQL_VERSAO
  FROM VENDEDORES v
 ORDER BY v.CODVEND
