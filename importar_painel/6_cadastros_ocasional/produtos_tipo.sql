SELECT t.CODIGO, t.DESCRICAO, t.ORDEM, t.ECOMMERCE, t.ESTMAX_SITE, t.GARANTIA_DIRETA, t.BLOQUEIA_ENCARGOS, t.ESTMIN_SITE,
       t.ATUALIZA2, CAST(SUBSTRING(t.DESCR_ECOMM FROM 1 FOR 255) AS VARCHAR(255)) AS DESCR_ECOMM, t.IMG_ECOMM,
       CAST(1 AS INTEGER) AS SQL_VERSAO
  FROM TIPO_PROD t
 ORDER BY t.CODIGO
