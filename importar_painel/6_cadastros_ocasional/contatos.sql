SELECT r.CODRET, r.CFT, r.CODIGO, r.NOME, r.FUNCAO, r.TIPO, r.EXCLUIDO, r.EMAIL, r.FONE, r.CELULAR, r.MSN, r.CPF, r.RG,
       r.PARTICIPACAO, r.NASCIMENTO, r.ENVEMAIL, r.ID_RADIO, r.USCADASTRO, r.DTCADASTRO, r.USALTERA, r.DTALTERA,
       IIF(COALESCE(TRIM(r.LOGIN), '') = '', 'N', 'S') AS TEM_LOGIN,
       CAST(1 AS INTEGER) AS SQL_VERSAO
  FROM RETIRANTES r
 WHERE r.CFT = 'C'
 ORDER BY r.CODRET
