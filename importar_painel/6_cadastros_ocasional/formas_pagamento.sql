SELECT f.CODIGO, f.DESCRICAO, f.PARCELAS, f.DIAS, f.DIAS_PARCELAS, f.TIPO, f.JUROS, f.LIBERADO, f.RETIRA, f.ATIVO, f.JUROS_PERC,
       f.ECOMMERCE, f.PARCELAS_SEM_JUROS, f.PARCELAS_MAXIMO, f.AMBIENTE, f.MODULO, f.BANDEIRA, f.FILIACAO, f.DESCONTO,
       f.JUROS_COMPOSTOS, f.UTILIZACAO_PERC, f.VALOR_MINIMO, f.VALOR_MINIMO_PARCELA, f.UTILIZACAO_VALOR, f.TAXA_CUSTOS, f.OBSERVACOES,
       CAST(1 AS INTEGER) AS SQL_VERSAO
  FROM FORMA_PAGAMENTO f
 ORDER BY f.CODIGO
