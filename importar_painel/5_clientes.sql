SELECT c.CODCLIENTE            AS CODCLIENTE,
       c.NOME                  AS NOME,
       c.FANTASIA              AS FANTASIA,
       c.CGC                   AS CGC,
       c.IE                    AS IE,
       c.PFPJ                  AS PFPJ,
       c.MEI                   AS MEI,
       c.SIMPLES               AS SIMPLES,
       c.VENDEDOR              AS VENDEDOR,
       CAST(c.VENDEDOR2 AS VARCHAR(12))      AS VENDEDOR2,
       c.CLI_VINCULADO         AS CLI_VINCULADO,
       c.TIPO                  AS TIPO,
       c.CADASTRO              AS CADASTRO,
       c.USUARIO_CADASTRO      AS USUARIO_CADASTRO,
       c.ALTERADO              AS ALTERADO,
       c.PROTESTO              AS PROTESTO,
       c.BLOQUEADO             AS BLOQUEADO,
       c.LIMITE                AS LIMITE,
       c.LIMUSADO              AS LIMUSADO,
       c.CREDITO               AS CREDITO,
       c.ENDERECO              AS ENDERECO,
       c.ENDERECO_NUMERO       AS ENDERECO_NUMERO,
       c.ENDERECO_COMPLEMENTO  AS ENDERECO_COMPLEMENTO,
       c.BAIRRO                AS BAIRRO,
       c.CIDADE                AS CIDADE,
       c.UF                    AS UF,
       c.CEP                   AS CEP,
       CAST(c.CODMUNIC AS VARCHAR(12))       AS CODMUNIC,
       c.FONE1                 AS FONE1,
       c.FONE2                 AS FONE2,
       c.FAX                   AS FAX,
       c.EMAIL                 AS EMAIL,
       c.WEBSITE               AS WEBSITE,
       c.COMPRADOR             AS COMPRADOR,
       c.FINANCEIRO            AS FINANCEIRO,
       c.FORMA_PAG_PADRAO      AS FORMA_PAG_PADRAO,
       CAST(c.TRANSP_PADRAO AS VARCHAR(12))  AS TRANSP_PADRAO,
       c.CNAE                  AS CNAE,
       c.TPAGRUP               AS TPAGRUP,
       CAST((SELECT MIN(x.CNAE) FROM CLIENTES_X_CNAE x
              WHERE x.CODCLIENTE = c.CODCLIENTE AND x.PRIMARIA = 'S') AS VARCHAR(12)) AS CNAE_PRINCIPAL,
       CAST(2 AS INTEGER) AS SQL_VERSAO
  FROM CLIENTES c
 ORDER BY c.CODCLIENTE
